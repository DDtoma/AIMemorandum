#!/usr/bin/env python3
"""Generate third-party Cargo notices without inventing attribution text."""

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tomllib

ROOT = Path(__file__).resolve().parents[1]
TEXT_PREFIXES = ("LICENSE", "LICENCE", "COPYING", "NOTICE")


def package_key(package):
    return (
        str(package["name"]),
        str(package["version"]),
        str(package["source"]),
    )


def repo_display_path(path):
    try:
        return path.resolve().relative_to(ROOT).as_posix()
    except ValueError:
        return path.name


def load_metadata(args):
    if args.metadata_json:
        return json.loads(args.metadata_json.read_text(encoding="utf-8"))
    command = [
        args.cargo,
        "metadata",
        "--format-version",
        "1",
        "--locked",
        "--manifest-path",
        str(args.manifest_path),
    ]
    if args.offline:
        command.append("--offline")
    result = subprocess.run(
        command,
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
        encoding="utf-8",
    )
    return json.loads(result.stdout)


def upstream_text_files(package):
    manifest = Path(package["manifest_path"])
    package_root = manifest.parent
    candidates = []
    declared = package.get("license_file")
    if declared:
        declared_path = Path(declared)
        path = declared_path if declared_path.is_absolute() else package_root / declared_path
        display = path.name if declared_path.is_absolute() else declared_path.as_posix()
        candidates.append((display, path))
    try:
        children = sorted(package_root.iterdir(), key=lambda item: item.name)
    except OSError:
        children = []
    for child in children:
        if child.name.upper().startswith(TEXT_PREFIXES) and child.is_file():
            candidates.append((child.name, child))

    unique = []
    seen = set()
    for display, path in candidates:
        identity = os.path.normcase(str(path.resolve()))
        if identity in seen or not path.is_file():
            continue
        seen.add(identity)
        unique.append((display, path))
    return unique


def fence_for(text):
    runs = [len(match.group(0)) for match in re.finditer(r"`+", text)]
    return "`" * max(3, (max(runs) + 1) if runs else 3)


def render(metadata, lock_bytes, lockfile):
    lock = tomllib.loads(lock_bytes.decode("utf-8"))
    locked_packages = sorted(
        package_key(package)
        for package in lock.get("package", [])
        if package.get("source")
    )
    packages = sorted(
        (package for package in metadata.get("packages", []) if package.get("source")),
        key=package_key,
    )
    metadata_packages = [package_key(package) for package in packages]
    if metadata_packages != locked_packages:
        missing = sorted(set(locked_packages) - set(metadata_packages))
        extra = sorted(set(metadata_packages) - set(locked_packages))
        raise RuntimeError(
            "Cargo metadata does not match the lockfile; "
            f"missing={missing!r}, extra={extra!r}"
        )

    texts = []
    text_ids = {}
    inventory = []
    for package in packages:
        key = package_key(package)
        references = []
        for display, path in upstream_text_files(package):
            data = path.read_bytes()
            digest = hashlib.sha256(data).hexdigest()
            if digest not in text_ids:
                try:
                    text = data.decode("utf-8-sig").replace("\r\n", "\n").replace("\r", "\n")
                except UnicodeDecodeError as error:
                    raise RuntimeError(
                        f"{key[0]} {key[1]} license/notice file {display} is not UTF-8"
                    ) from error
                text_ids[digest] = f"T{len(texts) + 1:03d}"
                texts.append(
                    {
                        "id": text_ids[digest],
                        "digest": digest,
                        "text": text,
                        "locations": [],
                    }
                )
            text_id = text_ids[digest]
            location = f"{key[0]} {key[1]}:{display}"
            texts[int(text_id[1:]) - 1]["locations"].append(location)
            references.append((text_id, display, digest))
        inventory.append((package, references))

    lines = [
        "# Third-Party Notices",
        "",
        "<!-- @generated by scripts/generate-third-party-notices.py; do not edit manually. -->",
        "",
        "AIMemorandum is licensed under GPL-3.0-only; see the root `LICENSE`.",
        "The third-party Cargo packages resolved for the desktop workspace remain under",
        "their own licenses.",
        "",
        "## Scope and provenance",
        "",
        f"- Inventory source: `{repo_display_path(lockfile)}` (SHA-256 of LF-normalized bytes: `{hashlib.sha256(lock_bytes).hexdigest()}`),",
        "  cross-checked against `cargo metadata --locked --format-version 1`.",
        f"- This document lists {len(packages)} third-party packages from the resolved desktop workspace,",
        "  including transitive and target-specific packages. It is a lockfile superset, not a",
        "  claim that every package is linked into every binary.",
        "- License expressions come from each upstream package's Cargo metadata. They are",
        "  reported verbatim and are not legal conclusions or replacements for required notices.",
        "- Full texts below come only from the resolved upstream package sources: a declared",
        "  `license_file`, plus root files named `LICENSE*`, `LICENCE*`, `COPYING*`, or `NOTICE*`.",
        "  Texts are UTF-8 decoded and line endings normalized to LF; SHA-256 values identify",
        "  the original bytes. No copyright statements or missing license texts are synthesized.",
        "- **No upstream license/notice text collected** means the declared metadata is still",
        "  shown, but that package needs separate upstream review for attribution and license",
        "  obligations. Absence from this document does not disclaim those obligations.",
        "- Cargo.lock does not inventory operating-system libraries, compiler runtimes, or",
        "  external packaging tools; their redistribution terms are outside this document.",
        "",
        "Regenerate after dependency changes with `python scripts/generate-third-party-notices.py`;",
        "verify a clean checkout with the same command plus `--check`. Add `--offline` only when",
        "all resolved crate sources are already available locally.",
        "",
        "## Package inventory",
        "",
    ]
    for package, references in inventory:
        name, version, source = package_key(package)
        lines.extend(
            [
                f"### {name} {version}",
                "",
                f"- Source: `{source}`",
                f"- Declared license: `{package.get('license') or 'not declared'}`",
            ]
        )
        if references:
            rendered = ", ".join(
                f"`{text_id}` (`{display}`, SHA-256 `{digest}`)"
                for text_id, display, digest in references
            )
            lines.append(f"- Collected license/notice texts: {rendered}")
        else:
            lines.append("- **No upstream license/notice text collected.**")
        lines.append("")

    lines.extend(["## Collected license and notice texts", ""])
    for entry in texts:
        lines.extend(
            [
                f"### {entry['id']}",
                "",
                f"SHA-256: `{entry['digest']}`",
                "",
                "Source locations:",
                "",
            ]
        )
        lines.extend(f"- {location}" for location in entry["locations"])
        lines.append("")
        fence = fence_for(entry["text"])
        lines.extend([fence + "text", entry["text"]])
        if not entry["text"].endswith("\n"):
            lines.append("")
        lines.extend([fence, ""])
    return "\n".join(lines).rstrip() + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cargo", default=os.environ.get("CARGO", "cargo"))
    parser.add_argument("--manifest-path", type=Path, default=ROOT / "apps/desktop/Cargo.toml")
    parser.add_argument("--lockfile", type=Path, default=ROOT / "apps/desktop/Cargo.lock")
    parser.add_argument("--output", type=Path, default=ROOT / "THIRD_PARTY_NOTICES.md")
    parser.add_argument("--metadata-json", type=Path, help=argparse.SUPPRESS)
    parser.add_argument("--offline", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    try:
        lock_bytes = args.lockfile.read_bytes().replace(b"\r\n", b"\n")
        rendered = render(load_metadata(args), lock_bytes, args.lockfile).encode("utf-8")
        if args.check:
            if not args.output.is_file() or args.output.read_bytes() != rendered:
                print(f"outdated notices: {args.output}; run the generator", file=sys.stderr)
                return 1
            print(f"up to date: {args.output}")
            return 0
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_bytes(rendered)
        print(f"wrote {args.output}")
        return 0
    except (OSError, KeyError, ValueError, RuntimeError, subprocess.CalledProcessError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
